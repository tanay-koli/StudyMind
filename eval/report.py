"""
StudyMind — Eval report: recompute metrics from eval/results/*.json and rewrite the README's
<!-- eval:start --> ... <!-- eval:end --> section with the results table and a Mermaid chart.

Usage: python -m eval.report
"""

import re
import sys
from collections import Counter
from pathlib import Path

from core.config import settings
from eval import metrics
from eval.configs import CONFIGS, ORDER
from eval.judge import agreement, load_labels, load_results

EVAL_DIR = Path(__file__).resolve().parent
README = EVAL_DIR.parent / "README.md"
START, END = "<!-- eval:start -->", "<!-- eval:end -->"
KAPPA_MIN = 0.6


def _mean(values) -> float | None:
    values = [v for v in values if v is not None]
    return sum(values) / len(values) if values else None


def summarise(result: dict, dataset: dict[str, dict]) -> dict:
    """Metrics over the rows that ran without error; unanswerable rows only count toward refusal.

    Rows whose id is no longer in the dataset are stale: counted, never scored.
    """
    known = [r for r in result["rows"] if r["id"] in dataset]
    ok = [r for r in known if not r["error"]]
    gold = {r["id"]: dataset[r["id"]]["gold"] for r in ok}
    kind = {r["id"]: dataset[r["id"]]["type"] for r in ok}
    answerable = [r for r in ok if kind[r["id"]] != "unanswerable"]
    diagram = [r for r in ok if kind[r["id"]] == "diagram"]
    judge = lambda r, m: (r.get("judge") or {}).get(m)  # noqa: E731
    return {
        "recall5": _mean(metrics.recall_at(r["hits"], gold[r["id"]]) for r in answerable),
        "mrr": _mean(metrics.mrr(r["hits"], gold[r["id"]]) for r in answerable),
        "faithfulness": _mean(judge(r, "faithfulness") for r in ok),
        "correctness": _mean(judge(r, "correctness") for r in answerable),
        "refusal": _mean(float(r["refused"]) for r in ok if kind[r["id"]] == "unanswerable"),
        "latency": _mean(r["latency_s"] for r in ok),
        "cost": _mean(r["cost_usd"] for r in ok),
        "n": len(known),
        "stale": len(result["rows"]) - len(known),
        "errors": len(known) - len(ok),
        "unjudged": sum("judge" not in r for r in ok),
        "judge_failures": sum("judge" in r and ((not r["refused"] and judge(r, "faithfulness") is None)
                                                or (r in answerable and judge(r, "correctness") is None))
                              for r in ok),
        "diagram": {"recall5": _mean(metrics.recall_at(r["hits"], gold[r["id"]]) for r in diagram),
                    "correctness": _mean(judge(r, "correctness") for r in diagram)},
    }


def _pct(v):
    return "—" if v is None else f"{v * 100:.1f}"


def _num(v, fmt):
    return "—" if v is None else format(v, fmt)


def _judge_line(labels: list[dict], results: dict) -> tuple[str, bool]:
    a = agreement(labels, results)
    model = (settings.judge_model or settings.llm_model).split("/", 1)[-1]
    if not a["n"]:
        return f"Judge ({model}): **judge unvalidated** — no hand labels yet.", False
    ok = all(a[m]["kappa"] >= KAPPA_MIN for m in ("correctness", "faithfulness"))
    parts = "; ".join(f"{m} {a[m]['agree'] * 100:.0f}% agree, κ {a[m]['kappa']:.2f}"
                      for m in ("correctness", "faithfulness"))
    return (f"Judge ({model}) vs {a['n']} hand labels: {parts}."
            + ("" if ok else f" **judge unvalidated** (κ < {KAPPA_MIN})")), ok


def build(results: dict[str, dict], dataset: dict[str, dict], labels: list[dict]) -> str:
    stats = {n: summarise(results[n], dataset) for n in ORDER if n in results}
    types = Counter(r["type"] for r in dataset.values())
    judge_line, validated = _judge_line(labels, results)
    tag = "" if validated else " (unvalidated)"
    out = [
        f"_{len(dataset)} questions ({', '.join(f'{t} {c}' for t, c in sorted(types.items()))}). "
        "Generated by `python -m eval.report`._",
        "",
        judge_line,
        "",
        f"| Config | Change | Recall@5 (%) | MRR | Faithfulness{tag} (%) | Correctness{tag} (%) "
        "| Refusal on unanswerable (%) | Latency (s) | Cost / q ($) |",
        "|---|---|---|---|---|---|---|---|---|",
        "| A | Cognee baseline (current app) | not measured (Cognee removed in Phase 1) | | | | | | |",
    ]
    for name, s in stats.items():
        tags = ([f"n={s['n']}/{len(dataset)}"] if s["n"] != len(dataset) else []) +                [f"{k}: {s[k]}" for k in ("stale", "errors") if s[k]]
        label = name + (f" ({', '.join(tags)})" if tags else "")
        out.append(f"| {label} | {CONFIGS[name]['change']} | {_pct(s['recall5'])} | {_num(s['mrr'], '.2f')} | "
                   f"{_pct(s['faithfulness'])} | {_pct(s['correctness'])} | {_pct(s['refusal'])} | "
                   f"{_num(s['latency'], '.1f')} | {_num(s['cost'], '.4f')} |")
    unjudged = [n for n, s in stats.items() if s["unjudged"]]
    if unjudged:
        out += ["", f"Not judged yet: {', '.join(unjudged)} (run `python -m eval.judge <config>`)"]
    failures = {n: s["judge_failures"] for n, s in stats.items() if s["judge_failures"]}
    if failures:
        out += ["", "Judge failures (unparseable replies, left out of the means): "
                + ", ".join(f"{n} {c}" for n, c in failures.items())]

    diagram = {n: s["diagram"] for n, s in stats.items() if s["diagram"]["recall5"] is not None}
    if diagram:
        out += ["", "Diagram-only questions:", "", "| Config | Recall@5 (%) | Correctness (%) |", "|---|---|---|"]
        out += [f"| {n} | {_pct(d['recall5'])} | {_pct(d['correctness'])} |" for n, d in diagram.items()]

    charted = {n: s["recall5"] for n, s in stats.items() if s["recall5"] is not None}
    if charted:
        out += ["", "```mermaid", "xychart-beta", '    title "Recall@5 by config"',
                "    x-axis [" + ", ".join(f'"{n}"' for n in charted) + "]",
                '    y-axis "Recall@5 (%)" 0 --> 100',
                "    bar [" + ", ".join(f"{v * 100:.1f}" for v in charted.values()) + "]", "```"]
    return "\n".join(out)


def update_readme(readme: Path, section: str) -> None:
    """Replace the marked section (or append one), keeping the file's own line endings."""
    with readme.open(encoding="utf-8", newline="") as f:
        text = f.read()
    eol = "\r\n" if "\r\n" in text else "\n"
    block = eol.join([START, *section.split("\n"), END])
    if START in text and END in text:
        text = re.sub(re.escape(START) + ".*?" + re.escape(END), lambda _: block, text, count=1, flags=re.S)
    else:
        text += f"{eol}## Evaluation{eol}{eol}{block}{eol}"
    with readme.open("w", encoding="utf-8", newline="") as f:
        f.write(text)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    from eval.run import load_dataset

    dataset = {r["id"]: r for r in load_dataset(EVAL_DIR / "dataset.jsonl")}
    results = load_results()
    update_readme(README, build(results, dataset, load_labels()))
    print(f"Updated {README} from {len(results)} result files")


if __name__ == "__main__":
    main()
